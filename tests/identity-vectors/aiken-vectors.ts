/**
 * The Aiken module that checks the published identifier and allowlist
 * vectors with the contract code: `cbor.serialise` and `blake2b_256` for the
 * identifiers (Part 1 §3.1), `allowlist.member` for the proofs that the
 * TypeScript helper built (Part 2 §3.4). `aiken check` runs it.
 */
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { REPO_ROOT, type AllowlistVectors, type IdentifierVector } from "./vectors.js";

export const AIKEN_VECTOR_MODULE = join(
  REPO_ROOT,
  "contracts/identity-marketplace/lib/identity_marketplace/properties/published_vectors.ak",
);

const bytes = (hex: string): string => `#"${hex}"`;
const bytesList = (items: readonly string[]): string => `[${items.map(bytes).join(", ")}]`;

export function renderAikenVectors(identifiers: readonly IdentifierVector[], allowlist: AllowlistVectors): string {
  const lines: string[] = [
    "//// Published vectors of Part 2 §12.4, checked by the contract code.",
    "////",
    "//// GENERATED by `npx tsx tests/identity-vectors/generate.ts` from the vectors",
    "//// in `contracts/identity-marketplace/vectors/identifiers.json` and",
    "//// `allowlist.json`. Do not edit; run the generator again.",
    "////",
    "//// - Identifiers (Part 1 §3.1): `cbor.serialise(seed)` and",
    "////   `blake2b_256(cbor.serialise(seed))` of each seed.",
    "//// - `legacy_root` membership (Part 2 §3.4): the TypeScript allowlist helper",
    "////   of `@marketplace/shared/identity` built the trees and the proofs;",
    "////   `allowlist.member` accepts every proof and rejects every changed one.",
    "",
    "use aiken/cbor",
    "use aiken/collection/list",
    "use aiken/crypto.{blake2b_256}",
    "use cardano/transaction.{OutputReference}",
    "use identity_marketplace/identity/allowlist",
    "",
  ];
  identifiers.forEach((v, i) => {
    lines.push(
      `/// Seed ${v.txId}#${v.outputIndex}.`,
      `test identifier_vector_${i + 1}() {`,
      `  let seed = OutputReference { transaction_id: ${bytes(v.txId)}, output_index: ${v.outputIndex} }`,
      "  and {",
      `    cbor.serialise(seed) == ${bytes(v.serialisedSeed)},`,
      `    blake2b_256(cbor.serialise(seed)) == ${bytes(v.vectorId)},`,
      "  }",
      "}",
      "",
    );
  });
  for (const tree of allowlist.trees) {
    lines.push(
      `/// Every member of the tree of ${tree.name}.`,
      `test allowlist_${tree.name.replace(" ", "_")}_members() {`,
      `  let root = ${bytes(tree.root)}`,
      "  list.all(",
      `    [${tree.proofs.map((p) => `(${bytes(p.id)}, ${bytesList(p.proof)})`).join(", ")}],`,
      "    fn(member) {",
      "      let (id, proof) = member",
      "      allowlist.member(root, id, proof)",
      "    },",
      "  )",
      "}",
      "",
    );
  }
  allowlist.rejections.forEach((r, i) => {
    lines.push(
      `/// Rejected: ${r.description}.`,
      `test allowlist_rejection_${i + 1}() {`,
      `  !allowlist.member(${bytes(r.root)}, ${bytes(r.id)}, ${bytesList(r.proof)})`,
      "}",
      "",
    );
  });
  return lines.join("\n");
}

/** `source` as `aiken fmt` writes it. */
export function formatAiken(source: string): string {
  const result = spawnSync("aiken", ["fmt", "--stdin"], { input: source, encoding: "utf8", env: { ...process.env, NO_COLOR: "1" } });
  if (result.error !== undefined || result.status !== 0) throw new Error(`aiken fmt failed: ${result.error?.message ?? result.stderr}`);
  return result.stdout;
}
