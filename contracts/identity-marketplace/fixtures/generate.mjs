#!/usr/bin/env node
// Writes fixtures/cbor-fixtures.json from the tests of
// lib/identity_marketplace/cbor_fixtures.ak.
//
// Run from contracts/identity-marketplace, with aiken v1.1.21 on PATH:
//   node fixtures/generate.mjs           write the file
//   node fixtures/generate.mjs --check   exit 1 when the file is not up to date

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const MODULE = "identity_marketplace/cbor_fixtures";
const projectDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(projectDir, "fixtures", "cbor-fixtures.json");

function fail(message) {
  console.error(message);
  process.exit(1);
}

// When stdout is not a terminal, `aiken check` prints its test report as JSON.
const run = spawnSync(
  "aiken",
  [
    "check",
    "--match-tests",
    MODULE,
    "--trace-filter",
    "user-defined",
    "--trace-level",
    "verbose",
  ],
  { cwd: projectDir, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);
if (run.error) fail(`Cannot run aiken: ${run.error.message}`);

let report;
try {
  report = JSON.parse(run.stdout);
} catch {
  process.stderr.write(run.stderr ?? "");
  fail("aiken check printed no JSON report. Run `aiken check` in a terminal to see the error.");
}

const module = report.modules?.find((m) => m.name === MODULE);
if (!module || module.tests.length === 0) fail(`No tests found in ${MODULE}.`);

const fixtures = {};
for (const test of module.tests) {
  if (test.status !== "pass") fail(`Fixture test ${test.title} did not pass.`);
  if (!Array.isArray(test.traces) || test.traces.length !== 3) {
    fail(`Fixture test ${test.title} must trace exactly 3 lines (type, cbor, diagnostic).`);
  }
  const [type, hex, diagnostic] = test.traces;
  if (!/^(?:[0-9a-fA-F]{2})+$/.test(hex)) fail(`Fixture test ${test.title} traced no CBOR hex.`);
  fixtures[test.title] = { type, cbor: hex.toLowerCase(), diagnostic };
}

const names = Object.keys(fixtures).sort();
const text = `${JSON.stringify(
  {
    description:
      "Plutus Data CBOR (hex, from cbor.serialise) and CBOR diagnostic notation of sample values of the identity-marketplace types. Generated by fixtures/generate.mjs. Do not edit by hand.",
    source: "lib/identity_marketplace/cbor_fixtures.ak",
    fixtures: Object.fromEntries(names.map((name) => [name, fixtures[name]])),
  },
  null,
  2,
)}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    // A missing file is out of date.
  }
  if (current !== text) fail("fixtures/cbor-fixtures.json is not up to date. Run: node fixtures/generate.mjs");
  console.log(`fixtures/cbor-fixtures.json is up to date (${names.length} fixtures).`);
} else {
  writeFileSync(outFile, text);
  console.log(`Wrote ${names.length} fixtures to fixtures/cbor-fixtures.json.`);
}
